const assert=require('node:assert/strict'),C=require('../webapp/market-flow-core.js');
const row=(code,foreign,close=10)=>({code,name:code,kind:code.startsWith('00')?'etf':'stock',exchange:'TWSE',foreign,close,currency:'TWD',trust:0,dealer:0,volume:1000,shortChange:5});
const days=[{date:'2026-11-19',rows:[row('00981A',-100),row('2330',200)]},{date:'2026-11-20',rows:[row('00981A',-200,12),row('2330',-100)]}];
const navs={'00981A':{'2026-11-19':{nav:10,premium:0},'2026-11-20':{nav:13,premium:-7.69}}};
const result=C.aggregate(days,navs,{'00981A':{active:true,domestic:true}}),etf=result[0];
assert.equal(etf.foreign,-300);assert.equal(etf.amount,-3400,'sum daily estimates, never multiply all shares by latest price');
assert.equal(etf.trust,0);assert.equal(etf.flowRatio,-15);assert.equal(etf.nav,13);assert.equal(etf.signals.length,3);assert.equal(etf.streak,-2);
assert.equal(C.aggregate(days,{'00981A':{'2026-11-19':{nav:10,premium:-1}}},{})[0].premium,null,'never use a different NAV date');
assert.equal(C.aggregate(days,{'00981A':{'2026-11-20':{nav:12,premium:0}}},{})[0].premium,0,'keep zero premiums');
const missing=C.aggregate([{date:'2026-11-19',rows:[]},days[1]],navs,{});
assert.equal(missing[0].foreign,null);assert.equal(missing[0].amount,null);assert.equal(missing[0].signals.length,2);
const fx=C.aggregate([{date:'2026-11-20',rows:[{...row('00636K',100),currency:'FX'}]}],{},{});
assert.equal(fx[0].amount,null);assert.equal(fx[0].foreign,100);
assert.equal(C.rank([...result,...fx],'amount','sell').length,1);
assert.equal(C.rank(result,'foreign','buy').length,1);
const state={market:'all',kind:'activeDomestic',query:'',watch:false};
assert.equal(C.filter(result,state).length,1);assert.equal(C.filter(result,{...state,query:'台積電'}).length,0);
assert.equal(C.filter(result,{...state,kind:'all',watch:true}).length,1);
const csv=C.csv([{...etf,name:'=HYPERLINK("bad")'}]);assert(csv.includes("'=HYPERLINK"));assert(csv.includes('00981A'));
console.log('Market flow: date joins, daily estimates, missingness, FX separation, rankings, signals, CSV safety passed');
